-- Ideal metafield mix per store: T-shirts (collar | designs), Shirts (designs). IDEAL_MIX is a share 0..1.
SELECT TRY_TO_NUMBER(BRANCH_CODE) AS BC, 'T-SHIRTS' AS CATEGORY,
       TRIM(COLLAR) || ' | ' || TRIM(DESIGNS) AS MIX_KEY,
       SUM(TRY_TO_NUMBER(REPLACE(IDEAL_MIX, '%', ''), 10, 3)) / 100 AS IDEAL_MIX
FROM SNITCH_DB.MAPLEMONK.GS_T_SHIRTS_IDEAL_MIX
WHERE TRY_TO_NUMBER(BRANCH_CODE) IS NOT NULL
GROUP BY 1, 2, 3
UNION ALL
SELECT TRY_TO_NUMBER(BRANCH_CODE), 'SHIRTS', TRIM(DESIGNS),
       SUM(TRY_TO_NUMBER(REPLACE(IDEAL_MIX, '%', ''), 10, 3)) / 100
FROM SNITCH_DB.MAPLEMONK.GS_SHIRTS_IDEAL_MIX
WHERE TRY_TO_NUMBER(BRANCH_CODE) IS NOT NULL
GROUP BY 1, 2, 3
