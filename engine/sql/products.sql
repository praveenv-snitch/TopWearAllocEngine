-- One row per in-scope SKU group: attributes, image, price, WH stock by zone + size, new/old signals.
WITH md AS (
    SELECT md.*, UPPER(TRIM(md.SKU_GROUP)) s,
           {MD_CAT_SYN} cat_syn
    FROM SNITCH_DB.MAPLEMONK.METAFIELDS_DATA md
    WHERE md.SKU_GROUP IS NOT NULL AND {SKU_EXCL}
    QUALIFY ROW_NUMBER() OVER (PARTITION BY UPPER(TRIM(md.SKU_GROUP)) ORDER BY md.STATUS = 'ACTIVE' DESC) = 1
),
cat AS (
    SELECT md.*,
           CASE WHEN s LIKE 'MP-4%' THEN SUBSTR(s, 4) ELSE s END b
    FROM md
),
prod AS (
    SELECT cat.*, COALESCE(cat_syn, {CATEGORY_PREFIX_CASE}) CATEGORY_N
    FROM cat
),
bp AS (
    SELECT UPPER(TRIM(SKU_GROUP)) s, ANY_VALUE(IMAGE_URL) IMAGE_URL, MIN(FINAL_LIVE_DATE) FINAL_LIVE_DATE,
           MAX(ORIGINAL_PRICE) ORIGINAL_PRICE, MAX(CURRENT_SLASHED_PRICE) SLASHED_PRICE,
           MAX(COST_PRICE) COST_PRICE, ANY_VALUE(L1_CATEGORY) L1_CATEGORY
    FROM SNITCH_DB.MAPLEMONK.BASE_PRODUCT GROUP BY 1
),
av AS (
    SELECT UPPER(TRIM(SKU_GROUP)) s, MAX(PRICE) PRICE, MAX(FINAL_ROS) ONLINE_ROS, MAX(NATURAL_ROS) ONLINE_NROS,
           ANY_VALUE(SKU_CLASS) SKU_CLASS, MIN(LIVE_DATE) LIVE_DATE
    FROM SNITCH_DB.MAPLEMONK.AVAILABILITY_MASTER_V2 GROUP BY 1
),
ism AS (    -- fabric weight / composition only exist in the image-search snapshot; optional enrichment
    SELECT UPPER(TRIM(SKU_GROUP)) s, ANY_VALUE(FABRIC_WEIGHT) FABRIC_WEIGHT, ANY_VALUE(COMPOSITION) COMPOSITION
    FROM SNITCH_DB.MAPLEMONK.IMAGE_SEARCH_MASTER GROUP BY 1
),
wh AS (     -- warehouse stock by zone (North / South) and size
    SELECT UPPER(TRIM(SKU_GROUP)) s,
        SUM(IFF(WAREHOUSE_LOCATION = 'North', AVAILABLE_UNITS, 0)) WH_N,
        SUM(IFF(WAREHOUSE_LOCATION = 'South', AVAILABLE_UNITS, 0)) WH_S,
        ARRAY_CONSTRUCT(
          SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(XS_UNITS,0),0)),  SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(S_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(M_UNITS,0),0)),   SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(L_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(XL_UNITS,0),0)),  SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(XXL_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(XL3_UNITS,0),0)), SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(XL4_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(XL5_UNITS,0),0)), SUM(IFF(WAREHOUSE_LOCATION='North',COALESCE(XL6_UNITS,0),0))) WH_N_SZ,
        ARRAY_CONSTRUCT(
          SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(XS_UNITS,0),0)),  SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(S_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(M_UNITS,0),0)),   SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(L_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(XL_UNITS,0),0)),  SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(XXL_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(XL3_UNITS,0),0)), SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(XL4_UNITS,0),0)),
          SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(XL5_UNITS,0),0)), SUM(IFF(WAREHOUSE_LOCATION='South',COALESCE(XL6_UNITS,0),0))) WH_S_SZ
    FROM SNITCH_DB.MAPLEMONK.AVAILABILITY_MASTER_V2_MERGED
    WHERE COALESCE(AVAILABLE_UNITS, 0) > 0
    GROUP BY 1
),
mech AS (
    SELECT UPPER(TRIM(SKU_GROUP)) s, MIN(WH_LIVE_DATE) WH_LIVE_DATE,
           LEAST(COALESCE(MIN(INWARD_DATE_NORTH), '9999-12-31'), COALESCE(MIN(INWARD_DATE_SOUTH), '9999-12-31')) FIRST_WH_INWARD,
           MAX(OFFLINE_ALLOCATED_STATUS) OFFLINE_ALLOCATED_STATUS
    FROM SNITCH_DB.MAPLEMONK.SKU_LIVE_MECH_V2 GROUP BY 1
),
offl AS (   -- offline history across all stores (exclusions applied)
    SELECT UPPER(SKU_GROUP) s, MIN(ORDER_DATE) FIRST_OFFLINE_SALE, MAX(ORDER_DATE) LAST_OFFLINE_SALE,
           SUM(COALESCE(SUBORDER_QUANTITY, 1)) OFFLINE_UNITS, COUNT(DISTINCT BRANCH_CODE) OFFLINE_STORES
    FROM SNITCH_DB.MAPLEMONK.STORE_FACT_ITEMS_OFFLINE
    WHERE COALESCE(DOC_PREFIX, '') NOT IN ({EXCL_DOC_PREFIX})
      AND MARKETPLACE_MAPPED NOT IN ({EXCL_MARKETPLACES})
      AND TRY_TO_NUMBER(BRANCH_CODE) NOT IN ({EXCL_BRANCHES})
      AND UPPER(SKU_GROUP) NOT LIKE 'CB%' AND UPPER(SKU_GROUP) NOT LIKE 'NT%'
    GROUP BY 1
),
rtn AS (
    SELECT UPPER(SKU_GROUP) s, SUM(COALESCE(SUBORDER_QUANTITY, 1)) OFFLINE_RETURNS
    FROM SNITCH_DB.MAPLEMONK.STORE_RETURNS_FACT_ITEMS
    WHERE MARKETPLACE_MAPPED NOT IN ({EXCL_MARKETPLACES})
    GROUP BY 1
)
SELECT
    p.s                                                         AS SKU,
    p.CATEGORY_N                                                AS CATEGORY,
    UPPER(p.STATUS)                                             AS STATUS,
    COALESCE(p.PRODUCT_NAME, p.TITLE)                           AS PRODUCT_NAME,
    p.COLLAR_NEW, p.MATERIAL_NEW, p.FIT, p.SLEEVE_TYPE, p.CLOSURE, p.POCKET, p.STYLE,
    p.OCCASSION_NEW, p.DESIGNS, COALESCE(p.PRINT_DESIGN_MAPPED, p.PRINT_DESIGN) AS PRINT_DESIGN, p.COLOR,
    ism.FABRIC_WEIGHT, ism.COMPOSITION,
    COALESCE(av.SKU_CLASS, p.SKU_CLASS)                         AS SKU_CLASS,
    bp.IMAGE_URL, bp.L1_CATEGORY,
    COALESCE(bp.ORIGINAL_PRICE, av.PRICE)                       AS MRP,
    COALESCE(bp.SLASHED_PRICE, av.PRICE)                        AS SELLING_PRICE,
    bp.COST_PRICE                                               AS COGS,
    COALESCE(bp.FINAL_LIVE_DATE, av.LIVE_DATE)                  AS FINAL_LIVE_DATE,
    ROUND(COALESCE(av.ONLINE_ROS, 0), 3)                        AS ONLINE_ROS,
    COALESCE(wh.WH_N, 0) WH_N, COALESCE(wh.WH_S, 0) WH_S, wh.WH_N_SZ, wh.WH_S_SZ,
    mech.WH_LIVE_DATE, NULLIF(mech.FIRST_WH_INWARD, '9999-12-31') AS FIRST_WH_INWARD, mech.OFFLINE_ALLOCATED_STATUS,
    offl.FIRST_OFFLINE_SALE, offl.LAST_OFFLINE_SALE,
    COALESCE(offl.OFFLINE_UNITS, 0) OFFLINE_UNITS, COALESCE(offl.OFFLINE_STORES, 0) OFFLINE_STORES,
    COALESCE(rtn.OFFLINE_RETURNS, 0) OFFLINE_RETURNS
FROM prod p
LEFT JOIN bp   ON bp.s = p.s
LEFT JOIN av   ON av.s = p.s
LEFT JOIN ism  ON ism.s = p.s
LEFT JOIN wh   ON wh.s = p.s
LEFT JOIN mech ON mech.s = p.s
LEFT JOIN offl ON offl.s = p.s
LEFT JOIN rtn  ON rtn.s = p.s
WHERE p.CATEGORY_N IN ({CATS})
