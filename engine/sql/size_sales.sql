-- Offline size-wise sales, last 90 days, per store x category (size curve for size split + size-health).
SELECT TRY_TO_NUMBER(BRANCH_CODE) AS BC,
       CASE WHEN UPPER(SKU_GROUP) REGEXP '^4(MSS|MSN|SHS|LSHS|BSHS|SFS|LSFS|BSFS).*' THEN 'SHIRTS' ELSE 'T-SHIRTS' END AS CATEGORY,
       UPPER(COALESCE(NULLIF(TRIM(SIZE), ''), REGEXP_SUBSTR(SKU, '[^-]+$'))) AS SZ,
       SUM(COALESCE(SUBORDER_QUANTITY, 1)) AS QTY
FROM SNITCH_DB.MAPLEMONK.STORE_FACT_ITEMS_OFFLINE
WHERE ORDER_DATE >= DATEADD(DAY, -90, CURRENT_DATE())
  AND COALESCE(DOC_PREFIX, '') NOT IN ({EXCL_DOC_PREFIX})
  AND MARKETPLACE_MAPPED NOT IN ({EXCL_MARKETPLACES})
  AND TRY_TO_NUMBER(BRANCH_CODE) NOT IN ({EXCL_BRANCHES})
  AND {PLUS_EXCL}
  AND UPPER(SKU_GROUP) REGEXP '^4(MSS|MSN|SHS|LSHS|BSHS|SFS|LSFS|BSFS|MST|RN|LRN|BRN|PL|LPL|BPL).*'
GROUP BY 1, 2, 3
