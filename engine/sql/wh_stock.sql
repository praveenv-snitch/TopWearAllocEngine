-- Warehouse sellable stock by zone (North / South) and size, Shirts + T-shirts.
SELECT UPPER(TRIM(SKU_GROUP)) SKU, UPPER(WAREHOUSE_LOCATION) ZONE,
       SUM(COALESCE(AVAILABLE_UNITS,0)) WH_UNITS,
       SUM(COALESCE(XS_UNITS,0)) W_XS, SUM(COALESCE(S_UNITS,0)) W_S, SUM(COALESCE(M_UNITS,0)) W_M,
       SUM(COALESCE(L_UNITS,0)) W_L, SUM(COALESCE(XL_UNITS,0)) W_XL, SUM(COALESCE(XXL_UNITS,0)) W_XXL,
       SUM(COALESCE(XL3_UNITS,0)) W_3XL, SUM(COALESCE(XL4_UNITS,0)) W_4XL,
       SUM(COALESCE(XL5_UNITS,0)) W_5XL, SUM(COALESCE(XL6_UNITS,0)) W_6XL
FROM SNITCH_DB.MAPLEMONK.AVAILABILITY_MASTER_V2_MERGED
WHERE UPPER(CATEGORY) IN ('SHIRTS','T-SHIRTS') AND COALESCE(AVAILABLE_UNITS,0) > 0
GROUP BY 1,2
